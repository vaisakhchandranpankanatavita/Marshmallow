import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--no-proxy-server'] });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
await page.goto('http://localhost:4000/about.html', { waitUntil: 'networkidle' });
await page.waitForTimeout(800);
let clip = await page.$eval('.story-scene:not(.is-active) .story-scene__inner', el => getComputedStyle(el).clipPath);
let activeClip = await page.$eval('.story-scene.is-active .story-scene__inner', el => getComputedStyle(el).clipPath);
console.log(`CLIP_INACTIVE ${clip.slice(0,60)} ACTIVE ${activeClip.slice(0,60)}`);
await page.mouse.wheel(0, 700);
await page.waitForTimeout(900);
let frameTx = await page.$eval('.story-scene.is-active .story-scene__frame', el => el.style.transform);
let cardTx = await page.$eval('.story-scene.is-active .story-scene__card', el => el.style.transform);
let sceneTx = await page.$eval('.story-scene.is-active', el => el.style.transform);
console.log(`FRAME_TX ${frameTx}`);
console.log(`CARD_TX ${cardTx}`);
console.log(`SCENE_3D ${sceneTx}`);
let frameParallax = frameTx.includes('translate3d') && frameTx.includes('rotate');
let cardParallax = cardTx.includes('translate3d') && cardTx.includes('translateZ');
console.log(`PARALLAX_FRAME ${frameParallax ? 'PASS' : 'FAIL'} CARD ${cardParallax ? 'PASS' : 'FAIL'}`);
await page.screenshot({ path: `M:\\money\\dropshipping\\verify-out\\about-creative-1280.png`, fullPage: false });
console.log('CREATIVE_SCREENSHOT done');
await browser.close();
